/** Self-hosted, pinned document libraries for source/static hosting as well as dist.
 * Run after changing package.json. No student content or third-party CDN is used.
 */
import {build} from "esbuild";
import {readFile,writeFile,copyFile,mkdir,rm} from "node:fs/promises";
import {createHash} from "node:crypto";
import path from "node:path";
import {fileURLToPath} from "node:url";

export async function buildBrowserVendor(root=process.cwd()) {
 const out=path.join(root,"vendor");
 const pkg=JSON.parse(await readFile(path.join(root,"package.json"),"utf8"));
 await rm(out,{recursive:true,force:true});
 await mkdir(out,{recursive:true});
 for(const name of ["pdf-lib","docx","jszip"]) {
  const contents=name==="jszip"?'import JSZip from "jszip"; export default JSZip;':`export * from "${name}";`;
  await build({
   stdin:{contents,resolveDir:root,sourcefile:name+"-browser-entry.js"},
   outfile:path.join(out,name+".js"),bundle:true,format:"esm",platform:"browser",
   target:["es2022"],minify:true,legalComments:"linked",logLevel:"silent"
  });
 }
 await copyFile(path.join(root,"node_modules/pdfjs-dist/legacy/build/pdf.min.mjs"),path.join(out,"pdfjs.mjs"));
 // The existing PDF importer resolves its worker from the site root.
 await copyFile(path.join(root,"node_modules/pdfjs-dist/legacy/build/pdf.worker.min.mjs"),path.join(root,"pdf.worker.min.mjs"));
 const licenses={"pdf-lib":"LICENSE.md",docx:"LICENSE",jszip:"LICENSE.markdown","pdfjs-dist":"LICENSE"};
 for(const [name,file] of Object.entries(licenses)) {
  await copyFile(path.join(root,"node_modules",name,file),path.join(out,name+"-LICENSE.txt"));
 }
 const files=["vendor/pdf-lib.js","vendor/docx.js","vendor/jszip.js","vendor/pdfjs.mjs","pdf.worker.min.mjs"];
 const sha256={};
 for(const file of files)sha256[file]=createHash("sha256").update(await readFile(path.join(root,file))).digest("hex");
 await writeFile(path.join(out,"manifest.json"),JSON.stringify({
  purpose:"Pinned browser-ready document libraries. Generated by scripts/build-browser-vendor.mjs.",
  packages:Object.fromEntries(Object.keys(licenses).map(name=>[name,pkg.dependencies[name]])),sha256
 },null,2)+"\n");
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))await buildBrowserVendor();

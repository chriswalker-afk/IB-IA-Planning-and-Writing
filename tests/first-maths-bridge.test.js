import test from "node:test";
import assert from "node:assert/strict";
import {createProjectState,normalizeProjectState} from "../src/core/project-state.js";
import {PLANNING_CATALOG} from "../src/planning/catalog.js";
import {escapeHtml,icon} from "../src/ui/primitives.js";
import {firstMathsContext,firstMathsExampleTopic,firstMathsTips,
 renderFirstMathsAdvice,renderFirstMathsSparks,renderFirstMathsExamples} from "../src/completing/first-maths-bridge.js";

const make=(kind="statistics",source="primary",route="relationships")=>{
 const s=createProjectState();
 s.route="completing";s.completion.current="C20";
 s.planning.fields.kind=kind;s.planning.fields.dataSource=source;
 s.planning.fields.aim="Does my mathematical question show a relationship?";
 s.planning.fields.primaryWhat="Measured lengths and times";
 s.planning.fields.secondaryPublisher="A published statistics service";
 s.planning.fields.secondaryVariables="Average values in seconds";
 s.planning.fields.course="AI SL";
 s.planning.routeExplorer.selectedRoute=route;
 return s;
};
test("Planning mathematics, route and source are reused without generating data or findings",()=>{
 const s=make();s.planning.mathSelected=["AI14","AI15"];
 const before=JSON.stringify(s);
 const ctx=firstMathsContext(s);
 assert.equal(ctx.sourceKey,"primary");
 assert.equal(ctx.source.title,"Primary data");
 assert.equal(ctx.activeRoute.id,"relationships");
 assert.equal(ctx.proposedMove,"Plot paired measurements");
 assert.equal(ctx.mathematicalQuestion,"What pattern, if any, is supported by the plotted values?");
 assert.deepEqual(ctx.selected.map(x=>x.id),["AI14","AI15"]);
 assert.equal(JSON.stringify(s),before);
 assert.equal(s.entries.length,0);
 const html=renderFirstMathsSparks(s,icon,escapeHtml);
 assert(html.includes("Primary data"));
 assert(html.includes("Measured lengths and times"));
 assert(html.includes("Plot paired measurements"));
 assert(html.includes("Relationships between two variables"));
 assert(html.includes("Mathematics you considered in Planning"));
 for(const id of ["AI14","AI15"]){
  const item=PLANNING_CATALOG.math.find(x=>x.id===id);
  assert(html.includes(escapeHtml(item.label)));
 }
 assert(html.includes('data-action="insight-jump"'));
 assert(html.includes('data-spark-library'));
 assert(!html.includes("24 measurements were collected"));
});
test("secondary and combined data give distinct contextual advice without confusing planned and actual",()=>{
 let s=make("modelling","secondary","fitted-models");
 let ctx=firstMathsContext(s);
 assert.equal(ctx.sourceKey,"secondary");
 assert.equal(ctx.source.title,"Secondary data");
 assert(ctx.source.guidance.includes("original source"));
 assert.equal(firstMathsExampleTopic(s),"model");
 let html=renderFirstMathsSparks(s,icon,escapeHtml);
 assert(html.includes("A published statistics service"));
 assert(!html.includes("Measured lengths and times"));
 s=make("statistics","both","relationships");
 ctx=firstMathsContext(s);
 assert.equal(ctx.sourceKey,"both");
 assert.equal(ctx.source.title,"Primary + secondary data");
 assert(ctx.source.guidance.includes("which source"));
 html=renderFirstMathsSparks(s,icon,escapeHtml);
 assert(html.includes("Primary: Measured lengths and times"));
 assert(html.includes("Secondary: A published statistics service"));
});

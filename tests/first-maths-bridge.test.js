test("help remains short, tailored, optional and safely escaped",()=>{
 const s=make("statistics","primary","relationships");
 s.planning.fields.aim='<img src=x onerror=alert(1)>';
 s.planning.fields.primaryWhat='<script>alert(1)</script>';
 let html=renderFirstMathsSparks(s,icon,escapeHtml);
 assert(!html.includes("<img"));
 assert(!html.includes("<script"));
 assert(html.includes("&lt;img"));
 assert(html.includes("&lt;script"));
 const tips=firstMathsTips(firstMathsContext(s));
 assert.equal(tips.length,4);
 assert(tips[0].detail.includes("Introduction"));
 assert(tips[2].detail.includes("sampling"));
 html=renderFirstMathsAdvice(s,icon,escapeHtml);
 assert.equal((html.match(/data-first-maths-tip=/g)||[]).length,4);
 assert(html.includes("Aim first. Then one useful mathematical step."));
 const reduced=renderFirstMathsAdvice(s,icon,escapeHtml,{reduced:true});
 assert(!reduced.includes("data-first-maths-tip="));
 assert(reduced.includes("Aim first"));
 const examples=renderFirstMathsExamples(s,icon,escapeHtml);
 assert(examples.includes('data-example-topic="graph"'));
 assert(examples.includes("data-writing-examples"));
 assert.equal((examples.match(/data-writing-examples/g)||[]).length,1);
});
test("old and new drafts preserve bridge choice, purpose and previous source records",()=>{
 const s=make();
 s.completion.fields.firstMathsBridgePlacement="intro";
 s.completion.fields.dataAimLink="The plot directly tests the main mathematical question";
 s.completion.fields.firstPurpose="Is there a pattern in the paired values?";
 s.completion.fields.actualSource="Actual observations collected at school";
 s.entries=[{id:"earlier",status:"completed",phase:"first",result:"A genuine mathematical result"}];
 const before=JSON.stringify(s),ctx=firstMathsContext(s);
 assert.equal(ctx.bridgePlacement,"intro");
 assert.equal(ctx.purposeNote,"Is there a pattern in the paired values?");
 assert.equal(JSON.stringify(s),before);
 const loaded=normalizeProjectState(JSON.parse(before));
 assert.equal(loaded.completion.fields.firstMathsBridgePlacement,"intro");
 assert.equal(loaded.completion.fields.dataAimLink,s.completion.fields.dataAimLink);
 assert.equal(loaded.completion.fields.firstPurpose,s.completion.fields.firstPurpose);
 assert.equal(loaded.entries[0].result,s.entries[0].result);
});
